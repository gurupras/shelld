//! Emits `table.go`: a two-stage lookup of `char::width()` for every Unicode
//! scalar value. Value encoding per codepoint: 0, 1, 2 = cell width, 3 = no
//! width (control character; alacritty drops these in `Term::input`).
use std::collections::HashMap;
use unicode_width::UnicodeWidthChar;

fn main() {
    const BLOCK: usize = 256;
    let mut blocks: Vec<Vec<u8>> = Vec::new();
    let mut index: HashMap<Vec<u8>, usize> = HashMap::new();
    let mut stage1: Vec<usize> = Vec::new();
    for b in 0..(0x110000 / BLOCK) {
        let mut blk = Vec::with_capacity(BLOCK / 4);
        let mut byte = 0u8;
        for i in 0..BLOCK {
            let cp = (b * BLOCK + i) as u32;
            let w: u8 = match char::from_u32(cp) {
                // U+17D8 (width 3) is special-cased in uniwidth.go.
                Some(c) => match c.width() {
                    Some(w) if w <= 2 => w as u8,
                    _ => 3,
                },
                None => 1,
            };
            byte |= w << ((i % 4) * 2);
            if i % 4 == 3 {
                blk.push(byte);
                byte = 0;
            }
        }
        let id = *index.entry(blk.clone()).or_insert_with(|| {
            blocks.push(blk);
            blocks.len() - 1
        });
        stage1.push(id);
    }
    assert!(blocks.len() <= 256, "stage1 must fit in a byte");

    println!("// Code generated by uniwidth/gen from unicode-width 0.2.2. DO NOT EDIT.");
    println!();
    println!("package uniwidth");
    println!();
    println!("// stage1 maps a codepoint's high bits (cp >> 8) to a block number.");
    print!("const stage1 = \"");
    for id in &stage1 {
        print!("\\x{:02x}", id);
    }
    println!("\"");
    println!();
    println!("// stage2 holds {} deduplicated 256-codepoint blocks, 2 bits per codepoint.", blocks.len());
    print!("const stage2 = \"");
    for blk in &blocks {
        for byte in blk {
            print!("\\x{:02x}", byte);
        }
    }
    println!("\"");
}
